package cmd

import (
	"fmt"
	"path/filepath"

	"octochan/core"

	"github.com/spf13/cobra"
)

var (
	fastMode   bool
	noSnapshot bool
)

var diffCmd = &cobra.Command{
	Use:     "diff <file1> <file2>",
	Short:   "Сравнить два конфигурационных файла",
	Example: "ochan diff prod.conf test.conf\ncat prod.conf | ochan diff - test.conf",
	Args:    cobra.RangeArgs(1, 2),
	RunE: func(cmd *cobra.Command, args []string) error {
		fm, err := mustFileManager()
		if err != nil {
			return err
		}

		left, err := readSource(args[0])
		if err != nil {
			return err
		}

		rightPath, err := argOrStdin(args, 1)
		if err != nil {
			return fmt.Errorf("для сравнения нужен второй файл: %w", err)
		}
		if left.Name == "stdin" && rightPath == "-" {
			return fmt.Errorf("нельзя использовать stdin для обоих файлов")
		}

		right, err := readSource(rightPath)
		if err != nil {
			return err
		}

		leftCfg, err := core.ParseConfig(left.Content)
		if err != nil {
			return fmt.Errorf("%s: %w", left.Name, err)
		}
		rightCfg, err := core.ParseConfig(right.Content)
		if err != nil {
			return fmt.Errorf("%s: %w", right.Name, err)
		}

		diff := core.CompareConfigs(leftCfg, rightCfg, left.Name, right.Name)
		if diff.Len() == 0 {
			cmd.Println("Файлы идентичны — различий не найдено.")
			return nil
		}

		cmd.Printf("Найдены различия (%d):\n", diff.Len())
		for _, entry := range diff.Entries {
			leftVal, rightVal := entry.Left, entry.Right
			if !entry.LeftExists {
				leftVal = "—"
			}
			if !entry.RightExists {
				rightVal = "—"
			}
			cmd.Printf("  %s: %s -> %s [%s]\n", entry.Param(), leftVal, rightVal, entry.Status)
		}

		// Отчёты и снапшоты пишутся в ~/.octochan, а не рядом с бинарником:
		// после установки в /usr/local/bin туда просто нет прав на запись.
		if fastMode {
			return nil
		}

		reportNum, err := core.GetNextReportNumber(fm.ReportsDir())
		if err != nil {
			return err
		}
		reportPath := filepath.Join(fm.ReportsDir(), fmt.Sprintf("diff_report_%d.txt", reportNum))
		if err := core.SaveDiffToFile(diff, reportPath); err != nil {
			return err
		}
		cmd.Printf("\nОтчёт сохранён: %s\n", reportPath)

		if noSnapshot {
			return nil
		}

		snapshot, err := core.CreateSnapshot(nil, diff, "system", "autogenerated")
		if err != nil {
			return err
		}
		if err := core.SaveSnapshot(snapshot, fm.SnapshotsDir()); err != nil {
			return err
		}
		cmd.Printf("Снапшот создан: %s\n", snapshot.ID)
		return nil
	},
}

func init() {
	diffCmd.Flags().BoolVarP(&fastMode, "fast", "f", false,
		"только вывод в консоль, без отчёта и снапшота")
	diffCmd.Flags().BoolVar(&noSnapshot, "no-snapshot", false,
		"не создавать снапшот")
}
