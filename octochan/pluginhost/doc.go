// Package pluginhost — хост подключаемых модулей команд.
//
// Модуль это отдельный исполняемый файл, который общается с октоханом
// по gRPC через hashicorp/go-plugin. Пакет отвечает за запуск, проверку
// контрольной суммы, взаимный TLS и перенос описаний команд cobra
// через protobuf в обе стороны.
//
// Имя pluginhost, а не plugin, чтобы не конфликтовать с пакетом
// hashicorp/go-plugin, который здесь же и импортируется.
//
// Пакет не зависит ни от config, ни от rlm: расширение системы командами
// не связано ни с движком конфигураций, ни с внешней автоматизацией.
