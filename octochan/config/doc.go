// Package config — движок сравнения и правки конфигураций.
//
// Пакет намеренно ничего не знает ни про PostgreSQL, ни про RLM, ни про
// систему плагинов и не зависит ни от одной внешней библиотеки. Он умеет
// четыре вещи и подходит для любой предметной области, где есть текстовые
// конфигурации:
//
//   - разобрать конфиг (ParseConfig) и записать обратно (SaveConfig);
//   - привести значение к канонической форме (NormalizeValue), чтобы
//     8GB и 8192MB считались одним и тем же;
//   - сравнить две конфигурации (CompareConfigs) и получить Diff;
//   - описать изменение планом (PlanFromDiff) и применить его (ApplyPlan).
//
// Откуда берётся конфигурация, пакет тоже не решает: источники
// регистрируют свою схему сами через RegisterSourceScheme. Файл читается
// встроенно, а живой сервер, удалённый узел или что угодно ещё
// подключается отдельным пакетом — см. pgsource как пример.
//
// Такое разделение сделано ради того, чтобы движок можно было брать
// отдельно: он полезен сам по себе и не должен тянуть за собой ни клиент
// внешней системы, ни хост плагинов.
